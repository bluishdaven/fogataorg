-- Profile photos: public to read (they appear next to names on public pages), writable only inside
-- the owner's folder: avatars/<user id>/<uuid>.webp. The browser crops and re-encodes every photo to
-- a 512px WebP before upload, so the bucket accepts nothing else.
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('avatars', 'avatars', true, 1048576, array['image/webp'])
on conflict (id) do update set
  public = excluded.public,
  file_size_limit = excluded.file_size_limit,
  allowed_mime_types = excluded.allowed_mime_types;
